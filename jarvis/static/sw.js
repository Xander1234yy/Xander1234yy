// Service worker: maakt Jarvis installeerbaar en laat de app direct openen.
// De app-schil wordt bewaard; gegevens (/api/) komen altijd live van de server.
const CACHE = "jarvis-v3";
const SHELL = ["/", "/manifest.webmanifest", "/icon-192.png", "/icon-180.png"];

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  // Eerst het netwerk (altijd de nieuwste versie), anders de bewaarde kopie.
  e.respondWith(fetch(e.request).then(res => {
    const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); return res;
  }).catch(() => caches.match(e.request).then(r => r || caches.match("/"))));
});
